// Bundles the in-page agent into a self-contained IIFE and exposes it to Node as a string module.
// Output: src/agent/agent-bundle.generated.ts (git-ignored). Run via `pnpm generate`.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const cliPkg = JSON.parse(
  await readFile(new URL("../../cli/package.json", import.meta.url), "utf8"),
);

const result = await build({
  entryPoints: [`${root}src/agent/entry.ts`],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["chrome110"],
  write: false,
  minify: false,
  legalComments: "none",
  define: { __MOTIONPR_VERSION__: JSON.stringify(cliPkg.version) },
  logLevel: "warning",
});

const source = result.outputFiles[0].text;
const banner = "// Generated by packages/capture/scripts/build-agent.mjs. Do not edit.\n";
await writeFile(
  `${root}src/agent/agent-bundle.generated.ts`,
  `${banner}export const AGENT_SOURCE: string = ${JSON.stringify(source)};\n`,
);
console.log(`agent bundle: ${(source.length / 1024).toFixed(1)} KB`);
