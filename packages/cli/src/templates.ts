import { MOTIONPR_PACKAGE, MOTIONPR_REPOSITORY } from "@motionpr/core";
import { PINNED_ACTIONS as A } from "./actions.ts";

export interface ConfigTemplateOptions {
  typescript: boolean;
  baseURL: string;
  devCommand: string | null;
  framework: string;
  exampleScenario: boolean;
  /** Animation engines found in package.json (`gsap`, `animejs`, `lenis`). */
  engines?: readonly string[];
}

const ENGINE_SETUP: Record<string, string> = {
  gsap: `GSAP: import { motionprGsap } from "${MOTIONPR_PACKAGE}/gsap"; motionprGsap.register(gsap);`,
  animejs: `Anime.js: import { createAnimeInstrumentation } from "${MOTIONPR_PACKAGE}/animejs"; use its wrapAnimate/wrapTimeline;`,
  lenis: `Lenis: import { motionprLenis } from "${MOTIONPR_PACKAGE}/lenis"; motionprLenis.attach(lenis);`,
};

function adaptersBlock(engines: readonly string[]): string {
  if (!engines.length)
    return `  // Animation engines (each is a no-op outside MotionPR captures):
  //   GSAP:     motionprGsap.register(gsap)                 (${MOTIONPR_PACKAGE}/gsap)
  //   Anime.js: createAnimeInstrumentation().wrapAnimate(…) (${MOTIONPR_PACKAGE}/animejs)
  //   Lenis:    motionprLenis.attach(lenis)                 (${MOTIONPR_PACKAGE}/lenis)
  // then list them so MotionPR reports when one does not register in the page:
  // adapters: [{ name: "gsap", required: true }],`;
  return `  // Detected in package.json. Connect each engine in your app (no-ops outside captures):
${engines.map((e) => `  //   ${ENGINE_SETUP[e]}`).join("\n")}
  // \`required\` makes a missing registration an error. See docs/integrations/.
  adapters: [
${engines.map((e) => `    { name: ${JSON.stringify(e)}, required: true },`).join("\n")}
  ],`;
}

/** The commented config written by `motionpr init`. Every option shown exists in the schema. */
export function configTemplate(o: ConfigTemplateOptions): string {
  const server = o.devCommand
    ? `
  // Start your app before capturing (skipped if it is already running locally).
  webServer: {
    command: ${JSON.stringify(o.devCommand)},
    url: ${JSON.stringify(o.baseURL)},
    reuseExistingServer: !process.env.CI,
    timeout: 120_000,
  },
`
    : `
  // Uncomment to let MotionPR start your app:
  // webServer: { command: "npm run dev", url: ${JSON.stringify(o.baseURL)}, reuseExistingServer: !process.env.CI },
`;
  const scenarios = o.exampleScenario
    ? `  scenarios: [
    {
      // Motion that plays when the page loads.
      id: "home-load",
      name: "Home page entrance",
      path: "/",
      steps: [{ type: "capture", label: "loaded" }],
    },
    // An interaction scenario. Point the selectors at your own UI:
    // {
    //   id: "menu-open",
    //   name: "Navigation menu opens",
    //   path: "/",
    //   steps: [
    //     { type: "click", selector: "[data-testid='menu-toggle']" },
    //     { type: "waitForAnimations" },
    //     { type: "capture", label: "menu-open" },
    //   ],
    // },
  ],`
    : `  scenarios: [
    { id: "home-load", path: "/", steps: [{ type: "capture", label: "loaded" }] },
  ],`;

  const head = o.typescript
    ? `import { defineConfig } from "${MOTIONPR_PACKAGE}";\n\nexport default defineConfig({`
    : `// @ts-check\nimport { defineConfig } from "${MOTIONPR_PACKAGE}";\n\nexport default defineConfig({`;
  return `${head}
  // Detected project type: ${o.framework}
  baseURL: ${JSON.stringify(o.baseURL)},
${server}
  browser: {
    // Engine to capture with: "chromium", "firefox" or "webkit". Each has its own baseline;
    // \`npx motionpr run --browser all\` captures with all three.
    name: "chromium",
    viewport: { width: 1440, height: 900 },
    // Run every scenario in several sizes:
    // viewports: [
    //   { name: "desktop", width: 1440, height: 900 },
    //   { name: "mobile", width: 390, height: 844, deviceScaleFactor: 2 },
    // ],
    colorScheme: "light",
  },

${scenarios}

  capture: {
    samples: 24, // property samples per animation
    frames: { enabled: true, fps: 30 }, // deterministic filmstrip for the report
  },

  comparison: {
    // Exit with code 1 when a difference at this severity (or worse) is found.
    failOn: "critical",
  },

  // Elements with changing content (clocks, carousels) can be excluded:
  // ignore: { selectors: [".live-clock"] },

${adaptersBlock(o.engines ?? [])}
});
`;
}

