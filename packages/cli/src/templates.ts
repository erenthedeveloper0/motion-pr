export function workflowTemplate(o: { packageManager: string; nodeVersion: string }): string {
  const install =
    o.packageManager === "pnpm"
      ? `      - uses: ${A.pnpmSetup}\n      - uses: ${A.setupNode}\n        with:\n          node-version: ${o.nodeVersion}\n          cache: pnpm\n      - run: pnpm install --frozen-lockfile`
      : o.packageManager === "yarn"
        ? `      - uses: ${A.setupNode}\n        with:\n          node-version: ${o.nodeVersion}\n          cache: yarn\n      - run: yarn install --frozen-lockfile`
        : `      - uses: ${A.setupNode}\n        with:\n          node-version: ${o.nodeVersion}\n          cache: npm\n      - run: npm ci`;
  const npx =
    o.packageManager === "pnpm" ? "pnpm exec" : o.packageManager === "yarn" ? "yarn" : "npx";
  return `# MotionPR: animation regression checks.
# See ${MOTIONPR_REPOSITORY}/blob/main/docs/ci/github-actions.md
# Third-party actions are pinned to full commit SHAs; Dependabot can keep them updated.
name: MotionPR

on:
  pull_request:
  push:
    branches: [main]

permissions:
  contents: read

jobs:
  motion:
    runs-on: ubuntu-latest
    timeout-minutes: 20
    steps:
      - uses: ${A.checkout}
${install}
      # Installs the engine in browser.name; list engines to install more (e.g. chromium firefox).
      - name: Install the browser for MotionPR
        run: ${npx} motionpr install --with-deps
      - name: Run MotionPR
        run: ${npx} motionpr run --ci
      - name: Upload MotionPR report
        if: \${{ always() }}
        uses: ${A.uploadArtifact}
        with:
          name: motionpr-report
          path: .motionpr/report
          if-no-files-found: ignore
          retention-days: 14
`;
}
